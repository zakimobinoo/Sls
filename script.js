const ADMIN_EMAIL = "admin@golfway.com";
let currentLang = localStorage.getItem('golfway-lang') || 'fa';

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('golfway-lang', lang);
  document.documentElement.lang = lang;
  document.body.dir = (lang === 'en') ? 'ltr' : 'rtl';

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      let txt = translations[lang][key];
      // Seamless infinite scroll: duplicate text so loop has no gap
      if (key === 'scrollText') {
        txt = txt + '\n\n' + txt;
      }
      el.textContent = txt;
    }
  });

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  updateItemInfos();
}

function updateItemInfos() {
  document.querySelectorAll('[data-fa]').forEach(el => {
    const v = el.getAttribute('data-' + currentLang);
    if (v) el.textContent = v;
  });
}


function initImageCycles() {
  document.querySelectorAll('.cycle-img-wrapper').forEach((wrapper, idx) => {
    const imgs = wrapper.querySelectorAll('.cycle-img');
    if (!imgs.length) return;
    let current = 0;
    imgs[0].classList.add('active');
    setInterval(() => {
      imgs[current].classList.remove('active');
      current = (current + 1) % imgs.length;
      setTimeout(() => {
        imgs[current].classList.add('active');
      }, 200);
    }, 4000 + idx * 700);
  });
}

let modalImages = [];
let modalIndex = 0;

function openModal(src, list) {
  const modal = document.getElementById('imageModal');
  const modalImg = document.getElementById('modalImage');
  if (!modal || !modalImg) return;
  if (list && list.length) {
    modalImages = list.slice();
    modalIndex = list.indexOf(src);
    if (modalIndex < 0) modalIndex = 0;
  } else if (src) {
    modalImages = [src];
    modalIndex = 0;
  } else {
    return;
  }
  modalImg.src = modalImages[modalIndex];
  modal.classList.add('active');
  updateModalCounter();
}


function closeModal() {
  const modal = document.getElementById('imageModal');
  if (modal) modal.classList.remove('active');
  modalImages = [];
  modalIndex = 0;
}

function modalNext() {
  if (!modalImages.length) return;
  modalIndex = (modalIndex + 1) % modalImages.length;
  const img = document.getElementById('modalImage');
  if (img) img.src = modalImages[modalIndex];
  updateModalCounter();
}

function modalPrev() {
  if (!modalImages.length) return;
  modalIndex = (modalIndex - 1 + modalImages.length) % modalImages.length;
  document.getElementById('modalImage').src = modalImages[modalIndex];
  updateModalCounter();
}

function modalNext() {
  if (!modalImages.length) return;
  modalIndex = (modalIndex + 1) % modalImages.length;
  document.getElementById('modalImage').src = modalImages[modalIndex];
  updateModalCounter();
}

function updateModalCounter() {
  const el = document.getElementById('modalCounter');
  if (el) {
    el.textContent = modalImages.length > 1 ? (modalIndex + 1) + ' / ' + modalImages.length : '';
    el.style.display = modalImages.length > 1 ? 'block' : 'none';
  }
  document.querySelectorAll('.modal-prev, .modal-next').forEach(btn => {
    if (btn) btn.style.display = modalImages.length > 1 ? 'block' : 'none';
  });
}

function initCarouselClicks() {
  // Event delegation — works for original + cloned carousel items
  document.addEventListener('click', (e) => {
    const el = e.target.closest('[data-images]');
    if (el) {
      e.preventDefault();
      const list = el.getAttribute('data-images').split('|').map(s => s.trim()).filter(Boolean);
      if (!list.length) return;
      openModal(list[0], list); // always open first photo of this code
      return;
    }
    const img = e.target.closest('.carousel-item img, .new-item-card img, .urgent-gallery img');
    if (img && !img.getAttribute('data-images')) {
      openModal(img.currentSrc || img.src);
    }
  });
}

