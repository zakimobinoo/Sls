let audioPlaying = false;
function toggleAudio() {
  const audio = document.getElementById('bgMusic');
  const btn = document.getElementById('audioBtn');
  if (!audio) return;
  if (audioPlaying) {
    audio.pause();
    if (btn) btn.textContent = '🎵';
  } else {
    audio.play().catch(() => {});
    if (btn) btn.textContent = '🔇';
  }
  audioPlaying = !audioPlaying;
}

function handleContactForm(e) {
  e.preventDefault();
  const name = document.getElementById('formName')?.value.trim() || '';
  const email = document.getElementById('formEmail')?.value.trim() || '';
  const subject = document.getElementById('formSubject')?.value.trim() || '';
  const message = document.getElementById('formMessage')?.value.trim() || '';
  if (!subject || !message) {
    alert(currentLang === 'fa' ? 'لطفا موضوع و پیام را پر کنید.' :
          currentLang === 'ar' ? 'يرجى ملء الموضوع والرسالة.' :
          'Please fill subject and message.');
    return;
  }
  const body = `Name: ${name}\nEmail: ${email}\n\n${message}`;
  window.location.href = `mailto:${ADMIN_EMAIL}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
}

function runSplash() {
  const splash = document.getElementById('splash');
  if (!splash) return;

  const already = sessionStorage.getItem('golfway-splash');
  if (already) {
    splash.classList.add('hide');
    return;
  }

  const w1 = document.getElementById('sw1');
  const w2 = document.getElementById('sw2');
  const w3 = document.getElementById('sw3');
  const logo = document.getElementById('splashLogo');

  setTimeout(() => w1 && w1.classList.add('show'), 400);
  setTimeout(() => w2 && w2.classList.add('show'), 1100);
  setTimeout(() => w3 && w3.classList.add('show'), 1800);
  setTimeout(() => {
    if (logo) {
      logo.classList.add('s1');
      setTimeout(() => { logo.classList.remove('s1'); logo.classList.add('s2'); }, 700);
      setTimeout(() => { logo.classList.remove('s2'); logo.classList.add('s3'); }, 1400);
    }
  }, 2500);

  setTimeout(() => {
    splash.classList.add('hide');
    sessionStorage.setItem('golfway-splash', '1');
  }, 4800);
}

function initMusicOnFirstClick() {
  const audio = document.getElementById('bgMusic');
  if (!audio) return;
  const start = () => {
    audio.play().then(() => {
      audioPlaying = true;
      const btn = document.getElementById('audioBtn');
      if (btn) btn.textContent = '🔇';
    }).catch(() => {});
    document.removeEventListener('click', start);
    document.removeEventListener('touchstart', start);
  };
  document.addEventListener('click', start, { once: true });
  document.addEventListener('touchstart', start, { once: true });
}

function initHomeFx() {
  if (!document.querySelector('.home-grid')) return;
  for (let i = 0; i < 8; i++) {
    const p = document.createElement('div');
    p.className = 'home-fx';
    p.style.left = Math.random() * 100 + '%';
    p.style.animationDelay = (Math.random() * 6) + 's';
    p.style.animationDuration = (6 + Math.random() * 5) + 's';
    p.style.width = p.style.height = (6 + Math.random() * 10) + 'px';
    document.body.appendChild(p);
  }
}

document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLang);
  runSplash();
  initImageCycles();
  initCarouselClicks();
  initMusicOnFirstClick();
  initHomeFx();

  const form = document.getElementById('contactForm');
  if (form) form.addEventListener('submit', handleContactForm);

  const modal = document.getElementById('imageModal');
  if (modal) {
    modal.addEventListener('click', (e) => {
      if (e.target === modal || e.target.closest('.modal-close')) closeModal();
    });
  }
  document.addEventListener('keydown', (e) => { if (e.key === 'Escape') closeModal(); });
});
